std::optional<ArtifactId> artifact_id(std::string_view keyword) noexcept {
    const auto id = core::index_of(kKeywords, keyword);
    return id.has_value() ? std::optional{ArtifactId{static_cast<std::uint8_t>(*id)}} : std::nullopt;
}

std::string_view artifact_keyword(ArtifactId id) noexcept {
    return kKeywords[id.value()];
}

