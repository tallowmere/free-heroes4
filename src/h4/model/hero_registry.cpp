std::span<const HeroEntry> hero_registry() noexcept {
    return kHeroes;
}

const HeroEntry* hero_entry(int id) noexcept {
    if (id < 0 || static_cast<std::size_t>(id) >= kHeroes.size())
        return nullptr;
    return &kHeroes[static_cast<std::size_t>(id)];
}

std::optional<int> hero_id(std::string_view keyword) noexcept {
    for (std::size_t i = 0; i < kHeroes.size(); ++i)
        if (core::iequals(kHeroes[i].keyword, keyword))
            return static_cast<int>(i);
    return std::nullopt;
}

