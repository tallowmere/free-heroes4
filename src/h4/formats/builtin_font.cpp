Font Font::builtin() {
    Font font;
    font.first_char_ = kFirst;
    font.point_size_ = kLineStep;
    font.glyphs_.reserve(kRows.size());
    for (const auto& rows : kRows) {
        const auto [first, last] = inked(rows);
        Glyph glyph;
        glyph.width_       = first == last ? kSpaceWide : last - first;
        glyph.height_      = kSide;
        glyph.advance_pad_ = 1;
        glyph.pixels_.assign(static_cast<std::size_t>(glyph.width_ * kSide), 0);
        for (std::int32_t y = 0; y < kSide && first != last; ++y)
            for (std::int32_t x = first; x < last; ++x)
                if ((rows[static_cast<std::size_t>(y)] >> x) & 1)
                    glyph.pixels_[static_cast<std::size_t>(y * glyph.width_ + x - first)] = 0xF0;
        font.glyphs_.push_back(std::move(glyph));
    }
    return font;
}

