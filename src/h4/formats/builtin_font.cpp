[[nodiscard]] constexpr std::pair<std::int32_t, std::int32_t> inked(const std::array<std::uint8_t, kSide>& rows) noexcept {
    std::uint8_t all = 0;
    for (const std::uint8_t row : rows)
        all |= row;
    std::int32_t first = 0, last = kSide;
    while (first < kSide && ((all >> first) & 1) == 0)
        ++first;
    while (last > first && ((all >> (last - 1)) & 1) == 0)
        --last;
    return {first, last};
}

